/**
 * Bundles the CLI into action/ripen.mjs, one file with no imports besides
 * Node built-ins, so the GitHub Action runs without installing anything.
 *
 *   node scripts/build-action.ts           write the bundle (after `pnpm build`)
 *   node scripts/build-action.ts --check   fail if the committed bundle is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const target = join(root, 'action/ripen.mjs');

export function bundle(): string {
  const index = readFileSync(join(root, 'packages/cli/dist/index.js'), 'utf8');
  const main = readFileSync(join(root, 'packages/cli/dist/main.js'), 'utf8');
  if (/^import .* from '\.\//m.test(index)) throw new Error('cli/index.js imports a local module; extend the bundler');
  const body = index.replace(/^export (async function|function|class|const) /gm, '$1 ');
  const entry = main.replace(/^#!.*\n/, '').replace(/^import \{ run \} from '\.\/index\.js';\n/m, '');
  return `#!/usr/bin/env node\n// Generated by scripts/build-action.ts from packages/cli. Do not edit.\n${body}\n${entry}`;
}

if (process.argv[1] === import.meta.filename) {
  const fresh = bundle();
  if (process.argv.includes('--check')) {
    const current = readFileSync(target, 'utf8');
    if (current !== fresh) {
      console.error('action/ripen.mjs is out of date: run pnpm build && node scripts/build-action.ts');
      process.exit(1);
    }
    console.log('action/ripen.mjs is up to date');
  } else {
    writeFileSync(target, fresh);
    console.log(`wrote ${target}`);
  }
}
